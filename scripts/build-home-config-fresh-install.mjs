async function main() {
  const available = (await readdir(migrationsDirectory))
    .filter((name) => name.endsWith(".sql"))
    .sort();
  const classified = new Set(HOME_CONFIG_MIGRATIONS);
  const unclassified = available.filter((name) => !classified.has(name));
  const missing = HOME_CONFIG_MIGRATIONS.filter(
    (name) => !available.includes(name),
  );

  if (unclassified.length > 0 || missing.length > 0) {
    throw new Error(
      `Classify every migration before generating the fresh-install SQL. Unknown: ${unclassified.join(", ") || "none"}. Missing: ${missing.join(", ") || "none"}.`,
    );
  }

  const sections = await Promise.all(
    HOME_CONFIG_MIGRATIONS.map(async (name) => {
      const source = await readFile(resolve(migrationsDirectory, name), "utf8");
      return `-- BEGIN ${name}\n${source.trim()}\n-- END ${name}`;
    }),
  );
  const header = [
    "-- Fresh-install HOME_CONFIG schema for a new Supabase project.",
    "-- Generated by: node scripts/build-home-config-fresh-install.mjs",
    "-- Do not run against an existing or shared project.",
    "-- Tenant migrations are isolated from catalog migrations under supabase-catalog/.",
    "",
  ].join("\n");

  await writeFile(defaultOutput, `${header}${sections.join("\n\n")}\n`, "utf8");
  process.stdout.write(
    `Created ${defaultOutput} from ${HOME_CONFIG_MIGRATIONS.length} HOME_CONFIG migrations.\n`,
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : "Unknown error.");
  process.exitCode = 1;
});
